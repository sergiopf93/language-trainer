const plurals: Record<string, string> = {
  'it-letto': 'letti',
  'it-casa': 'case',
  'it-citta': 'città',
  'it-caffe': 'caffè',
  'it-hotel': 'hotel',
};

export function extendVocabulary(
  previous: VocabularyEntry[],
  lessons: Lesson[],
): VocabularyEntry[] {
  const entries = [...previous, ...structuredClone(additions)];
  for (const entry of entries) {
    if (plurals[entry.id] && !entry.forms.some((f) => f.key === 'plural')) {
      entry.version = String(Number(entry.version) + 1);
      entry.forms.push({
        key: 'plural',
        text: plurals[entry.id],
        features: { number: 'plural' },
        irregular: ['it-citta', 'it-caffe', 'it-hotel'].includes(entry.id),
      });
      entry.provenance +=
        ' Ampliación C08: plural canónico del repertorio; candidate.';
    }
    const associated = lessons.filter((l) =>
      l.vocabularyIds.includes(entry.id),
    );
    entry.conceptIds = associated.map((l) => 'it-a1-c' + l.code);
    entry.topicIds = [
      ...new Set(associated.map((l) => 'it-a1-t' + l.code.slice(0, 2))),
    ];
    entry.tags = [
      ...new Set([
        ...entry.tags,
        ...associated.map((l) => 'C' + l.code.slice(0, 2)),
      ]),
    ];
  }
  return entries;
}
