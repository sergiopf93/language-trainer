export function extendC18C25Vocabulary(
  previous: VocabularyEntry[],
  lessons: Lesson[],
): VocabularyEntry[] {
  const entries = [...structuredClone(previous), ...structuredClone(additions)];
  for (const entry of entries) {
    const extension = extensions[entry.id];
    if (extension) {
      entry.version = String(Number(entry.version) + 1);
      entry.gloss = extension.gloss;
      entry.forms.push(...(extension.forms ?? []));
      entry.provenance +=
        ' Ampliación de usos C18–C25; candidate, revisión pendiente.';
    }
    const associated = lessons.filter((l) =>
      l.vocabularyIds.includes(entry.id),
    );
    entry.conceptIds = associated.map((l) => 'it-a1-c' + l.code);
    entry.topicIds = [
      ...new Set(associated.map((l) => 'it-a1-t' + l.code.slice(0, 2))),
    ];
    entry.tags = [
      ...new Set([
        ...entry.tags,
        ...associated.map((l) => 'C' + l.code.slice(0, 2)),
      ]),
    ];
  }
  return entries;
}
